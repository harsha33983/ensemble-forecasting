"""
Database Initialization and Schema Generation Module.

Ensures the SQLite database is created, all 7 tables are initialized,
exports the DDL to database/schema.sql, and verifies table presence.
"""

from pathlib import Path
from typing import Any, Dict, List, Optional
import sqlite3

from sqlalchemy import inspect
from sqlalchemy.engine import Engine
from sqlalchemy.schema import CreateTable

from src.config import DATABASE_DIR, DATABASE_FILE, DATABASE_SCHEMA_FILE, DATABASE_URL
from src.database.connection import get_engine
from src.database.models import (
    Base,
    CrossValidationResult,
    Dataset,
    FeatureImportance,
    Forecast,
    ModelRun,
    Prediction,
    SystemLog,
)
from src.utils import setup_logger

logger = setup_logger("database_init")

EXPECTED_TABLES = [
    "datasets",
    "model_runs",
    "predictions",
    "forecasts",
    "feature_importance",
    "cross_validation_results",
    "system_logs",
]


def export_schema_sql(engine: Engine, output_file: Path = DATABASE_SCHEMA_FILE) -> Path:
    """
    Generate and save complete SQLite DDL schema script into database/schema.sql.
    """
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    ddl_statements = []
    # Order matters for foreign keys
    tables_in_order = [
        Dataset.__table__,
        ModelRun.__table__,
        Prediction.__table__,
        Forecast.__table__,
        FeatureImportance.__table__,
        CrossValidationResult.__table__,
        SystemLog.__table__,
    ]

    for table in tables_in_order:
        create_stmt = str(CreateTable(table).compile(engine))
        ddl_statements.append(create_stmt.strip() + ";\n")

    # Add index statements
    index_statements = [
        "CREATE INDEX IF NOT EXISTS idx_predictions_model_run_id ON predictions(model_run_id);",
        "CREATE INDEX IF NOT EXISTS idx_predictions_timestamp ON predictions(timestamp);",
        "CREATE INDEX IF NOT EXISTS idx_forecasts_model_run_id ON forecasts(model_run_id);",
        "CREATE INDEX IF NOT EXISTS idx_forecasts_date ON forecasts(forecast_date);",
        "CREATE INDEX IF NOT EXISTS idx_feature_importance_model_run_id ON feature_importance(model_run_id);",
        "CREATE INDEX IF NOT EXISTS idx_cv_results_model_run_id ON cross_validation_results(model_run_id);",
        "CREATE INDEX IF NOT EXISTS idx_system_logs_created_at ON system_logs(created_at);",
    ]

    full_sql = "-- SQLite Database Schema for Ensemble Forecasting System\n"
    full_sql += "-- Auto-generated by database_init.py\n\n"
    full_sql += "PRAGMA foreign_keys = ON;\n\n"
    full_sql += "\n".join(ddl_statements)
    full_sql += "\n-- Indexes\n" + "\n".join(index_statements) + "\n"

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(full_sql)

    logger.info("Exported SQLite schema DDL to %s", output_path)
    return output_path


def init_db(db_url: Optional[str] = None, force_recreate: bool = False) -> Dict[str, Any]:
    """
    Initialize SQLite database, create tables, export schema.sql, and verify integrity.
    """
    engine = get_engine(db_url=db_url)

    if force_recreate:
        logger.warning("Dropping existing tables for clean recreation...")
        Base.metadata.drop_all(engine)

    logger.info("Creating database tables if not existing...")
    Base.metadata.create_all(engine)

    # Export schema.sql
    schema_path = export_schema_sql(engine)

    # Verify tables
    inspector = inspect(engine)
    existing_tables = inspector.get_table_names()
    missing_tables = [t for t in EXPECTED_TABLES if t not in existing_tables]

    is_valid = len(missing_tables) == 0
    if not is_valid:
        logger.error("Database initialization INCOMPLETE. Missing tables: %s", missing_tables)
    else:
        logger.info("All 7 required database tables verified successfully: %s", existing_tables)

    return {
        "database_url": str(engine.url),
        "database_file": str(DATABASE_FILE),
        "tables_verified": existing_tables,
        "is_valid": is_valid,
        "missing_tables": missing_tables,
        "schema_file": str(schema_path),
    }


if __name__ == "__main__":
    result = init_db()
    print("Database Initialized:", result)

